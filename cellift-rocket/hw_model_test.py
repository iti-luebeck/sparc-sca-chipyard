def hw(x: int) -> int:
    return bin(x).count("1")

def load_csv_group(results_dir: str, prefix: str, n: int = 256):
    """Load group_a_000 ... group_a_N-1 CSVs. Returns array (N, T) of HW deltas."""
    traces = []
    for i in range(n):
        path = os.path.join(results_dir, f"{prefix}_{i:03d}.csv")
        if not os.path.exists(path):
            raise FileNotFoundError(path)
        data = np.genfromtxt(path, delimiter=",", skip_header=1)
        hw_col = data[:, 2]  # hamming_weight_counter_t0 (column index 2)
        deltas = np.diff(hw_col, prepend=0.0)
        traces.append(deltas)
    return np.array(traces, dtype=float)   # (N, T)

def load_plaintext_byte(results_dir: str, prefix: str, byte_idx: int, n: int = 256):
    """Load plaintext byte values from scenario manifest files."""
    import json, pathlib
    manifest_dir = pathlib.Path(results_dir).parent / "sw" / "_manifests"
    # Try to load from manifest JSON
    pat = str(manifest_dir / f"multi_aes_unmasked_a_manifest.json")
    if not os.path.exists(pat):
        sys.exit(f"ERROR: Cannot find scenario manifest at {pat}\n"
                 "Run with --n-unmasked 256 first to generate scenario manifests.")
    with open(pat) as f:
        manifest = json.load(f)
    plaintexts = []
    for entry in manifest["scenarios"][:n]:
        p_bytes = bytes.fromhex(entry["patches"]["aes_plaintext"])
        plaintexts.append(p_bytes[byte_idx])
    return np.array(plaintexts, dtype=int)

def pearson_corr(x: np.ndarray, Y: np.ndarray) -> np.ndarray:
    """Pearson correlation of vector x (N,) with each column of Y (N, T). Returns (T,)."""
    x = x - x.mean()
    Y = Y - Y.mean(axis=0)
    num = (x[:, None] * Y).sum(axis=0)
    denom = np.sqrt((x**2).sum() * (Y**2).sum(axis=0)) + 1e-12
    return num / denom

def main():
    ap = argparse.ArgumentParser(description="HW-model DPA correlation for Rocket CellIFT")
    ap.add_argument("results_dir", help="Directory with group_a_*.csv / group_b_*.csv")
    ap.add_argument("--byte",  type=int, default=0, help="Target AES key byte index (0-15)")
    ap.add_argument("--n",     type=int, default=256, help="Number of traces (default 256)")
    ap.add_argument("--plot",  action="store_true")
    ap.add_argument("--out",   default=None, help="Output directory for plots/JSON")
    args = ap.parse_args()

    out_dir = args.out or args.results_dir
    os.makedirs(out_dir, exist_ok=True)

    print(f"Loading {args.n} traces from {args.results_dir} ...")
    try:
        traces_a = load_csv_group(args.results_dir, "group_a", args.n)
    except FileNotFoundError as e:
        sys.exit(f"ERROR: {e}\nRun with --n-unmasked {args.n} first.")

    print(f"Loading plaintext byte {args.byte} from scenario manifests ...")
    try:
        pt_bytes = load_plaintext_byte(args.results_dir, "group_a", args.byte, args.n)
    except SystemExit:
        raise
    except Exception as e:
        sys.exit(f"ERROR loading plaintexts: {e}")

    print(f"Computing Pearson correlation for all 256 key hypotheses ...")
    peak_corr = np.zeros(256)
    peak_cycle = np.zeros(256, dtype=int)
    for k in range(256):
        model = np.array([hw(SBOX[p ^ k]) for p in pt_bytes], dtype=float)
        corr = pearson_corr(model, traces_a)
        peak_corr[k] = np.max(np.abs(corr))
        peak_cycle[k] = int(np.argmax(np.abs(corr)))

    ranked = np.argsort(-peak_corr)   # descending by peak correlation
    correct_rank = int(np.where(ranked == ranked[0])[0][0]) + 1  # rank of top candidate

    print(f"\n=== HW Model DPA Results (byte {args.byte}) ===")
    print(f"Top key candidate: 0x{ranked[0]:02x}  (peak |r| = {peak_corr[ranked[0]]:.4f}, cycle {peak_cycle[ranked[0]]})")
    print(f"Top-5 candidates: {[f'0x{ranked[i]:02x}' for i in range(5)]}")
    print(f"(Correct rank is not known without ground-truth key)")

    if args.plot and HAVE_MPL:
        fig, ax = plt.subplots(figsize=(10, 4))
        ax.bar(range(256), peak_corr, color="steelblue", width=1.0)
        ax.set_xlabel("Key hypothesis")
        ax.set_ylabel("Peak |Pearson r|")
        ax.set_title(f"HW-model DPA — byte {args.byte}")
        out_png = os.path.join(out_dir, f"hw_model_byte{args.byte:02d}.png")
        fig.tight_layout()
        fig.savefig(out_png, dpi=120)
        plt.close(fig)
        print(f"Plot saved: {out_png}")
    elif args.plot:
        print("WARNING: matplotlib not available, skipping plot.")

    import json
    result = {
        "byte": args.byte,
        "n_traces": args.n,
        "top_key_candidate": int(ranked[0]),
        "top_peak_corr": float(peak_corr[ranked[0]]),
        "top_peak_cycle": int(peak_cycle[ranked[0]]),
        "ranked_keys": [int(k) for k in ranked],
    }
    out_json = os.path.join(out_dir, f"hw_model_byte{args.byte:02d}.json")
    with open(out_json, "w") as f:
        json.dump(result, f, indent=2)
    print(f"Results saved: {out_json}")

if __name__ == "__main__":
    main()
