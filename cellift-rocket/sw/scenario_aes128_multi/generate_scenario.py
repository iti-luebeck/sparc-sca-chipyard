#!/usr/bin/env python3
"""
AES-128 Multi-Executable Scenario Generator

Generates:
1. test_vectors.h - Header file with N test vectors (same key, random plaintexts)
2. run_all_simulations.sh - Shell script to run all simulations
3. Optionally builds all executables

Usage:
    python3 generate_scenario.py -n 10                    # Generate 10 vectors
    python3 generate_scenario.py -n 10 --build            # Generate and build
    python3 generate_scenario.py -n 10 --key 2b7e151628aed2a6abf7158809cf4f3c
    python3 generate_scenario.py -n 10 --build --run      # Generate, build, and run all sims
"""

import argparse
import os
import sys
import subprocess
from datetime import datetime

try:
    from Crypto.Cipher import AES
except ImportError:
    try:
        from Cryptodome.Cipher import AES
    except ImportError:
        print("Error: pycryptodome is required. Install with:")
        print("  pip install pycryptodome")
        sys.exit(1)


def generate_random_bytes(length=16):
    """Generate random bytes."""
    return os.urandom(length)


def bytes_to_hex_array(data, indent=4):
    """Convert bytes to C hex array format."""
    hex_vals = [f"0x{b:02x}" for b in data]
    line1 = ", ".join(hex_vals[:8])
    line2 = ", ".join(hex_vals[8:])
    spaces = " " * indent
    return f"{spaces}{{ {line1},\n{spaces}  {line2} }}"

def bytes_to_single_line(data):
    """Convert bytes to single-line C hex array."""
    hex_vals = [f"0x{b:02x}" for b in data]
    return "{ " + ", ".join(hex_vals) + " }"

def hex_string_to_bytes(hex_str):
    """Convert hex string to bytes."""
    hex_str = hex_str.replace(" ", "").replace("-", "").replace(":", "")
    if len(hex_str) != 32:
        raise ValueError(f"Key must be 32 hex characters (16 bytes), got {len(hex_str)}")
    return bytes.fromhex(hex_str)


def aes128_encrypt(plaintext, key):
    """Perform AES-128 ECB encryption."""
    cipher = AES.new(key, AES.MODE_ECB)
    return cipher.encrypt(plaintext)


def generate_test_vectors(num_vectors, key):
    """Generate test vectors with fixed key and random plaintexts."""
    vectors = []
    for _ in range(num_vectors):
        plaintext = generate_random_bytes(16)
        ciphertext = aes128_encrypt(plaintext, key)
        vectors.append((key, plaintext, ciphertext))
    return vectors


def generate_vector_headers(vectors, key):
    """Generate individual header files for each vector (vector_0.h, vector_1.h, etc.)."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    for i, (k, pt, ct) in enumerate(vectors):
        header = f'''/**
 * AES-128 Test Vector {i}
 * Auto-generated by generate_scenario.py at {timestamp}
 * Key: {key.hex()}
 */

#ifndef VECTOR_{i}_H
#define VECTOR_{i}_H

#include <stdint.h>

/* Test vector {i} */
static const uint8_t test_key[16] = {bytes_to_single_line(k)};
static const uint8_t test_plaintext[16] = {bytes_to_single_line(pt)};
static const uint8_t test_expected_ciphertext[16] = {bytes_to_single_line(ct)};

#endif /* VECTOR_{i}_H */
'''
        with open(f"vector_{i}.h", 'w') as f:
            f.write(header)
    
    return len(vectors)


def generate_header_file(vectors, output_file, key):
    """Generate C header file with test vectors."""
    num_vectors = len(vectors)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    header = f'''/**
 * AES-128 Test Vectors
 * 
 * Auto-generated by generate_scenario.py
 * Generated: {timestamp}
 * Number of vectors: {num_vectors}
 * Fixed key: {key.hex()}
 * 
 * Build separate executables with: make NUM_VECTORS={num_vectors}
 */

#ifndef TEST_VECTORS_H
#define TEST_VECTORS_H

#include <stdint.h>

/* Number of test vectors available */
#define NUM_TEST_VECTORS {num_vectors}

/* AES-128 Keys (all same key, but stored per-vector for flexibility) */
static const uint8_t keys[NUM_TEST_VECTORS][16] = {{
'''
    
    # Add keys (all same)
    key_entries = []
    for i in range(num_vectors):
        key_entries.append(bytes_to_hex_array(key))
    header += ",\n".join(key_entries)
    header += "\n};\n\n"
    
    # Add plaintexts
    header += "/* AES-128 Plaintexts (16 bytes each, randomly generated) */\n"
    header += "static const uint8_t plaintexts[NUM_TEST_VECTORS][16] = {\n"
    
    pt_entries = []
    for _, pt, _ in vectors:
        pt_entries.append(bytes_to_hex_array(pt))
    header += ",\n".join(pt_entries)
    header += "\n};\n\n"
    
    # Add expected ciphertexts
    header += "/* Expected Ciphertexts (16 bytes each) */\n"
    header += "static const uint8_t expected_ciphertexts[NUM_TEST_VECTORS][16] = {\n"
    
    ct_entries = []
    for _, _, ct in vectors:
        ct_entries.append(bytes_to_hex_array(ct))
    header += ",\n".join(ct_entries)
    header += "\n};\n\n"
    
    header += "#endif /* TEST_VECTORS_H */\n"
    
    with open(output_file, 'w') as f:
        f.write(header)
    
    return output_file


def generate_run_script(num_vectors, output_file, simlen=8000):
    """Generate shell script to run all simulations."""
    
    script = f'''#!/bin/bash
#
# Run all AES-128 simulations
# Auto-generated by generate_scenario.py
#
# Usage:
#   ./run_all_simulations.sh                    # Run all vanilla sims
#   ./run_all_simulations.sh --cellift          # Run all CellIFT sims  
#   ./run_all_simulations.sh --single 5         # Run only vector 5
#   ./run_all_simulations.sh --range 0 9        # Run vectors 0-9
#   ./run_all_simulations.sh --simlen 10000     # Custom cycle count

# Get script directory
SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"

# Configuration
NUM_VECTORS={num_vectors}
SIMLEN={simlen}
TRACE_DIR="$SCRIPT_DIR/traces"
BUILD_DIR="$SCRIPT_DIR/build"

# Paths to simulators
CELLIFT_ROCKET_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
VANILLA_SIM="$CELLIFT_ROCKET_DIR/build/run_vanilla_trace_0.1/default-verilator/Vtop_tiny_soc"
CELLIFT_SIM="$CELLIFT_ROCKET_DIR/build/run_cellift_trace/default-verilator/Vtop_tiny_soc"

# Colors
RED='\\033[0;31m'
GREEN='\\033[0;32m'
YELLOW='\\033[1;33m'
NC='\\033[0m'

mkdir -p "$TRACE_DIR"

echo "=========================================="
echo "AES-128 Multi-Simulation Runner"
echo "=========================================="
echo "Build dir: $BUILD_DIR"
echo "Trace dir: $TRACE_DIR"
echo ""

# Check executables
if [ ! -f "$BUILD_DIR/app_0.elf" ]; then
    echo -e "${{YELLOW}}Building executables...${{NC}}"
    cd "$SCRIPT_DIR" && make NUM_VECTORS=$NUM_VECTORS
fi

# Run simulation function
run_sim() {{
    local idx=$1
    local sim_type=$2
    
    local sim_bin="$VANILLA_SIM"
    local trace_ext="vcd"
    
    if [ "$sim_type" = "cellift" ]; then
        sim_bin="$CELLIFT_SIM"
        trace_ext="fst"
    fi
    
    local elf_file="$BUILD_DIR/app_${{idx}}.elf"
    local trace_file="$TRACE_DIR/${{sim_type}}_${{idx}}.${{trace_ext}}"
    
    if [ ! -f "$elf_file" ]; then
        echo -e "  ${{RED}}ERROR: $elf_file not found${{NC}}"
        return 1
    fi
    
    if [ ! -f "$sim_bin" ]; then
        echo -e "  ${{RED}}ERROR: Simulator not found${{NC}}"
        return 1
    fi
    
    echo -n "  Vector $idx ($sim_type)... "
    
    export SIMSRAMELF="$elf_file"
    export TRACEFILE="$trace_file"
    export SIMLEN="$SIMLEN"
    export SIMSRAMTAINT="/dev/null"
    
    local sim_dir="$(dirname "$sim_bin")"
    cd "$sim_dir"
    ./$(basename "$sim_bin") > /dev/null 2>&1
    cd "$SCRIPT_DIR"
    
    if [ -f "$trace_file" ]; then
        local size=$(du -h "$trace_file" | cut -f1)
        echo -e "${{GREEN}}OK${{NC}} ($size)"
        return 0
    else
        echo -e "${{YELLOW}}No trace${{NC}}"
        return 1
    fi
}}

# Parse arguments
SIM_TYPE="vanilla"
START_IDX=0
END_IDX=$((NUM_VECTORS - 1))

while [[ $# -gt 0 ]]; do
    case $1 in
        --cellift) SIM_TYPE="cellift"; shift ;;
        --vanilla) SIM_TYPE="vanilla"; shift ;;
        --range) START_IDX=$2; END_IDX=$3; shift 3 ;;
        --single) START_IDX=$2; END_IDX=$2; shift 2 ;;
        --simlen) SIMLEN=$2; shift 2 ;;
        -h|--help)
            echo "Usage: $0 [--vanilla|--cellift] [--single N] [--range A B] [--simlen N]"
            exit 0 ;;
        *) echo "Unknown: $1"; exit 1 ;;
    esac
done

echo "Simulation: $SIM_TYPE, Cycles: $SIMLEN, Vectors: $START_IDX-$END_IDX"
echo ""

SUCCESS=0
FAILED=0

for i in $(seq $START_IDX $END_IDX); do
    run_sim $i $SIM_TYPE && ((SUCCESS++)) || ((FAILED++))
done

echo ""
echo "=========================================="
echo "Summary: $SUCCESS successful, $FAILED failed"
echo "=========================================="
ls -lh "$TRACE_DIR"/*.${{trace_ext:-vcd}} 2>/dev/null | head -20
'''
    
    with open(output_file, 'w') as f:
        f.write(script)
    
    os.chmod(output_file, 0o755)
    return output_file


def main():
    parser = argparse.ArgumentParser(
        description="Generate AES-128 multi-executable scenario",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Generate 10 test vectors with NIST key
  %(prog)s -n 10

  # Generate with custom key and build
  %(prog)s -n 20 --key 000102030405060708090a0b0c0d0e0f --build

  # Generate, build, and prepare run scripts
  %(prog)s -n 100 --build
"""
    )
    
    parser.add_argument(
        "-n", "--num-vectors",
        type=int,
        required=True,
        help="Number of test vectors (and executables) to generate"
    )
    
    parser.add_argument(
        "--key",
        type=str,
        default="2b7e151628aed2a6abf7158809cf4f3c",  # NIST example key
        help="AES-128 key in hex (32 characters). Default: NIST example key"
    )
    
    parser.add_argument(
        "--build",
        action="store_true",
        help="Build all executables after generating"
    )
    
    parser.add_argument(
        "--simlen",
        type=int,
        default=8000,
        help="Simulation length in cycles (default: 8000)"
    )
    
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Random seed for reproducible generation"
    )
    
    args = parser.parse_args()
    
    # Set random seed if provided
    if args.seed is not None:
        import random
        random.seed(args.seed)
        global generate_random_bytes
        def generate_random_bytes(length=16):
            return bytes([random.randint(0, 255) for _ in range(length)])
    
    # Parse key
    try:
        key = hex_string_to_bytes(args.key)
    except ValueError as e:
        parser.error(str(e))
    
    print("=" * 50)
    print("AES-128 Multi-Executable Scenario Generator")
    print("=" * 50)
    print(f"Number of vectors: {args.num_vectors}")
    print(f"Key: {key.hex()}")
    print()
    
    # Generate test vectors
    print("Generating test vectors...")
    vectors = generate_test_vectors(args.num_vectors, key)
    
    # Generate individual header files (vector_0.h, vector_1.h, etc.)
    num_headers = generate_vector_headers(vectors, key)
    print(f"  Created: {num_headers} vector header files (vector_0.h ... vector_{num_headers-1}.h)")
    
    # Generate run script
    run_script = generate_run_script(args.num_vectors, "run_all_simulations.sh", args.simlen)
    print(f"  Created: {run_script}")
    
    # Print sample
    print()
    print("Sample (first vector):")
    _, pt, ct = vectors[0]
    print(f"  Key:        {key.hex()}")
    print(f"  Plaintext:  {pt.hex()}")
    print(f"  Ciphertext: {ct.hex()}")
    
    # Build if requested
    if args.build:
        print()
        print("Building executables...")
        result = subprocess.run(
            ["make", "clean"],
            capture_output=True,
            text=True
        )
        result = subprocess.run(
            ["make", f"NUM_VECTORS={args.num_vectors}"],
            capture_output=True,
            text=True
        )
        if result.returncode == 0:
            print(f"  Built {args.num_vectors} executables successfully")
            # Show sizes
            subprocess.run(["ls", "-lh", "build/"], capture_output=False)
        else:
            print(f"  Build failed!")
            print(result.stderr)
            return 1
    
    print()
    print("=" * 50)
    print("Next steps:")
    print("=" * 50)
    if not args.build:
        print(f"  1. Build executables:  make NUM_VECTORS={args.num_vectors}")
    print(f"  2. Run vanilla sims:   ./run_all_simulations.sh --vanilla")
    print(f"  3. Run CellIFT sims:   ./run_all_simulations.sh --cellift")
    print(f"  4. Run single sim:     ./run_all_simulations.sh --vanilla --single 5")
    print()
    
    return 0


if __name__ == "__main__":
    sys.exit(main())
