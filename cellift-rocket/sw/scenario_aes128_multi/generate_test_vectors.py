#!/usr/bin/env python3
"""
AES-128 Test Vector Generator

Generates test vectors for AES-128 encryption with:
- Random plaintexts
- Fixed or random keys
- Computed expected ciphertexts

Usage:
    python3 generate_test_vectors.py -n 10 -o test_vectors.h
    python3 generate_test_vectors.py -n 100 --fixed-key 000102030405060708090a0b0c0d0e0f -o my_vectors.h
    python3 generate_test_vectors.py -n 50 --random-keys -o random_vectors.h
"""

import argparse
import os
import sys
from datetime import datetime

try:
    from Crypto.Cipher import AES
except ImportError:
    try:
        from Cryptodome.Cipher import AES
    except ImportError:
        print("Error: pycryptodome is required. Install with:")
        print("  pip install pycryptodome")
        sys.exit(1)


def generate_random_bytes(length=16):
    """Generate random bytes."""
    return os.urandom(length)


def bytes_to_hex_array(data, indent=6):
    """Convert bytes to C hex array format."""
    hex_vals = [f"0x{b:02x}" for b in data]
    # Split into two lines of 8 bytes each
    line1 = ", ".join(hex_vals[:8])
    line2 = ", ".join(hex_vals[8:])
    spaces = " " * indent
    return f"{spaces}{{ {line1},\n{spaces}  {line2} }}"


def hex_string_to_bytes(hex_str):
    """Convert hex string to bytes."""
    # Remove any spaces or common separators
    hex_str = hex_str.replace(" ", "").replace("-", "").replace(":", "")
    if len(hex_str) != 32:
        raise ValueError(f"Key must be 32 hex characters (16 bytes), got {len(hex_str)}")
    return bytes.fromhex(hex_str)


def aes128_encrypt(plaintext, key):
    """Perform AES-128 ECB encryption."""
    cipher = AES.new(key, AES.MODE_ECB)
    return cipher.encrypt(plaintext)


def generate_test_vectors(num_vectors, fixed_key=None):
    """
    Generate test vectors.
    
    Args:
        num_vectors: Number of test vectors to generate
        fixed_key: If provided, use this key for all vectors. Otherwise random keys.
    
    Returns:
        List of (key, plaintext, ciphertext) tuples
    """
    vectors = []
    
    for i in range(num_vectors):
        # Generate key (fixed or random)
        if fixed_key is not None:
            key = fixed_key
        else:
            key = generate_random_bytes(16)
        
        # Generate random plaintext
        plaintext = generate_random_bytes(16)
        
        # Compute ciphertext
        ciphertext = aes128_encrypt(plaintext, key)
        
        vectors.append((key, plaintext, ciphertext))
    
    return vectors


def generate_header_file(vectors, output_file, fixed_key=None):
    """Generate C header file with test vectors."""
    
    num_vectors = len(vectors)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    # Determine key mode description
    if fixed_key is not None:
        key_mode = f"Fixed key: {fixed_key.hex()}"
    else:
        key_mode = "Random keys"
    
    header = f'''/**
 * AES-128 Test Vectors
 * 
 * Auto-generated by generate_test_vectors.py
 * Generated: {timestamp}
 * Number of vectors: {num_vectors}
 * Key mode: {key_mode}
 * 
 * Each test case consists of:
 * - 16-byte key
 * - 16-byte plaintext (random)
 * - 16-byte expected ciphertext
 */

#ifndef TEST_VECTORS_H
#define TEST_VECTORS_H

#include <stdint.h>

/* Number of test vectors to process */
#define NUM_TEST_VECTORS {num_vectors}

/* AES-128 Keys (16 bytes each) */
static const uint8_t keys[NUM_TEST_VECTORS][16] = {{
'''
    
    # Add keys
    key_entries = []
    for i, (key, pt, ct) in enumerate(vectors):
        comment = f"    /* Test Vector {i} */"
        hex_array = bytes_to_hex_array(key)
        key_entries.append(f"{comment}\n{hex_array}")
    
    header += ",\n\n".join(key_entries)
    header += "\n};\n\n"
    
    # Add plaintexts
    header += "/* AES-128 Plaintexts (16 bytes each) */\n"
    header += "static const uint8_t plaintexts[NUM_TEST_VECTORS][16] = {\n"
    
    pt_entries = []
    for i, (key, pt, ct) in enumerate(vectors):
        comment = f"    /* Test Vector {i} */"
        hex_array = bytes_to_hex_array(pt)
        pt_entries.append(f"{comment}\n{hex_array}")
    
    header += ",\n\n".join(pt_entries)
    header += "\n};\n\n"
    
    # Add expected ciphertexts
    header += "/* Expected Ciphertexts (16 bytes each) - for verification */\n"
    header += "static const uint8_t expected_ciphertexts[NUM_TEST_VECTORS][16] = {\n"
    
    ct_entries = []
    for i, (key, pt, ct) in enumerate(vectors):
        comment = f"    /* Test Vector {i} */"
        hex_array = bytes_to_hex_array(ct)
        ct_entries.append(f"{comment}\n{hex_array}")
    
    header += ",\n\n".join(ct_entries)
    header += "\n};\n\n"
    
    header += "#endif /* TEST_VECTORS_H */\n"
    
    # Write to file
    with open(output_file, 'w') as f:
        f.write(header)
    
    return output_file


def main():
    parser = argparse.ArgumentParser(
        description="Generate AES-128 test vectors for hardware simulation",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Generate 10 vectors with random keys
  %(prog)s -n 10 -o test_vectors.h

  # Generate 100 vectors with a fixed key
  %(prog)s -n 100 --fixed-key 000102030405060708090a0b0c0d0e0f -o fixed_key_vectors.h

  # Generate 50 vectors with random keys (explicit)
  %(prog)s -n 50 --random-keys -o random_vectors.h

  # Use NIST example key
  %(prog)s -n 20 --fixed-key 2b7e151628aed2a6abf7158809cf4f3c -o nist_key_vectors.h
"""
    )
    
    parser.add_argument(
        "-n", "--num-vectors",
        type=int,
        required=True,
        help="Number of test vectors to generate"
    )
    
    parser.add_argument(
        "-o", "--output",
        type=str,
        required=True,
        help="Output header file name"
    )
    
    key_group = parser.add_mutually_exclusive_group()
    key_group.add_argument(
        "--fixed-key",
        type=str,
        metavar="HEX",
        help="Use fixed key (32 hex characters, e.g., 000102030405060708090a0b0c0d0e0f)"
    )
    key_group.add_argument(
        "--random-keys",
        action="store_true",
        help="Use random keys for each vector (default)"
    )
    
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Random seed for reproducible generation"
    )
    
    args = parser.parse_args()
    
    # Validate arguments
    if args.num_vectors < 1:
        parser.error("Number of vectors must be at least 1")
    
    # Set random seed if provided
    if args.seed is not None:
        import random
        random.seed(args.seed)
        # Note: os.urandom doesn't use this seed, but we can use random instead
        global generate_random_bytes
        def generate_random_bytes(length=16):
            return bytes([random.randint(0, 255) for _ in range(length)])
    
    # Parse fixed key if provided
    fixed_key = None
    if args.fixed_key:
        try:
            fixed_key = hex_string_to_bytes(args.fixed_key)
        except ValueError as e:
            parser.error(str(e))
    
    # Generate vectors
    print(f"Generating {args.num_vectors} test vectors...")
    if fixed_key:
        print(f"Using fixed key: {fixed_key.hex()}")
    else:
        print("Using random keys")
    
    vectors = generate_test_vectors(args.num_vectors, fixed_key)
    
    # Generate header file
    output_path = generate_header_file(vectors, args.output, fixed_key)
    
    print(f"Generated {args.num_vectors} test vectors")
    print(f"Output written to: {output_path}")
    
    # Print summary
    print("\nSample (first vector):")
    key, pt, ct = vectors[0]
    print(f"  Key:        {key.hex()}")
    print(f"  Plaintext:  {pt.hex()}")
    print(f"  Ciphertext: {ct.hex()}")


if __name__ == "__main__":
    main()
