class TraceLoader:
    """Loads HD/HW CSV traces from WAL++ output"""
    
    @staticmethod
    def load_trace(csv_file: str) -> np.ndarray:
        """
        Load a single trace from CSV file.
        
        Expected CSV format (from WAL++):
            cycle,value (or similar)
            0,0
            1,5
            2,10
            ...
        """
        values = []
        try:
            with open(csv_file, 'r') as f:
                reader = csv.reader(f)
                next(reader)  # Skip header
                for row in reader:
                    if row:
                        try:
                            values.append(float(row[-1]))  # Take last column
                        except (ValueError, IndexError):
                            pass
        except Exception as e:
            raise ValueError(f"Error loading trace from {csv_file}: {e}")
        
        return np.array(values, dtype=np.float64)
    
    @staticmethod
    def load_all_traces(traces_dir: str, pattern: str = "*_hd.csv", 
                       max_traces: Optional[int] = None) -> Dict[int, np.ndarray]:
        """
        Load all matching traces from directory.
        
        Args:
            traces_dir: Directory containing CSV files
            pattern: Glob pattern for files (e.g., "*_hd.csv" or "*_hw.csv")
            max_traces: Maximum number of traces to load (None = all)
        
        Returns:
            Dictionary mapping trace index to trace array
        """
        traces_path = Path(traces_dir)
        trace_files = sorted(traces_path.glob(pattern))
        
        if not trace_files:
            raise FileNotFoundError(f"No trace files matching '{pattern}' found in {traces_dir}")
        
        if max_traces:
            trace_files = trace_files[:max_traces]
        
        traces = {}
        for trace_file in trace_files:
            # Extract index from filename - try multiple patterns
            # Patterns: "cellift_matmul_5_hd.csv", "vanilla_matmul_5_hd.csv", "matmul_5_hd.csv"
            match = re.search(r'(?:vanilla_|cellift_)?matmul_(\d+)', trace_file.name)
            if match:
                idx = int(match.group(1))
                traces[idx] = TraceLoader.load_trace(str(trace_file))
        
        return traces

