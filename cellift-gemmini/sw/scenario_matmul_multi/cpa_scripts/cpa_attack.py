def main():
    parser = argparse.ArgumentParser(
        description='Correlation Power Analysis Attack on Gemmini MatMul',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python3 cpa_attack.py --traces traces/ --matrices . --dim 4
  python3 cpa_attack.py --traces traces/ --matrices . --metric hd --output recovered_B.txt
  python3 cpa_attack.py --traces traces/ --matrices . --dim 4 --start-byte 0 --max-bytes 4
        """
    )
    
    parser.add_argument('--traces', required=True, 
                       help='Directory containing HD/HW CSV traces')
    parser.add_argument('--matrices', required=True,
                       help='Directory containing matrix_*.h header files')
    parser.add_argument('--dim', type=int, default=4,
                       help='Matrix dimension (default: 4)')
    parser.add_argument('--metric', choices=['hd', 'hw'], default='hd',
                       help='Power metric to use (default: hd)')
    parser.add_argument('--max-traces', type=int, default=None,
                       help='Maximum number of traces to use (default: all)')
    parser.add_argument('--start-byte', type=int, default=0,
                       help='Start attacking from this byte index (default: 0)')
    parser.add_argument('--max-bytes', type=int, default=None,
                       help='Maximum number of bytes to recover (default: all)')
    parser.add_argument('--output', default='recovered_B.txt',
                       help='Output file for recovered matrix B')
    parser.add_argument('--verbose', '-v', action='store_true',
                       help='Verbose output')
    
    args = parser.parse_args()
    
    print("=" * 80)
    print("Correlation Power Analysis (CPA) Attack - Gemmini MatMul")
    print("=" * 80)
    print()
    
    # Load configuration
    dim = args.dim
    matrix_size = dim * dim
    metric = args.metric
    traces_dir = args.traces
    matrices_dir = args.matrices
    
    print(f"Configuration:")
    print(f"  Matrix dimension: {dim}x{dim}")
    print(f"  Power metric: {metric.upper()}")
    print(f"  Traces directory: {traces_dir}")
    print(f"  Matrices directory: {matrices_dir}")
    print()
    
    # Load traces
    print(f"Loading {metric.upper()} traces...")
    trace_pattern = f"*_{metric}.csv"
    traces_dict = TraceLoader.load_all_traces(traces_dir, pattern=trace_pattern, 
                                              max_traces=args.max_traces)
    
    if not traces_dict:
        print(f"ERROR: No traces found matching pattern '{trace_pattern}'")
        sys.exit(1)
    
    num_traces = len(traces_dict)
    print(f"  Loaded {num_traces} traces")
    if args.verbose:
        print(f"  Trace indices: {sorted(list(traces_dict.keys())[:5])}...")
    print()
    
    # Load matrix pairs
    print(f"Loading matrix header files from {matrices_dir}...")
    matrices_path = Path(matrices_dir)
    matrix_files = sorted(matrices_path.glob('matrix_*.h'))
    
    if not matrix_files:
        print(f"ERROR: No matrix_*.h files found in {matrices_dir}")
        print(f"  Current working directory: {os.getcwd()}")
        print(f"  Absolute path: {matrices_path.resolve()}")
        sys.exit(1)
    
    matrix_pairs = {}
    for matrix_file in matrix_files:
        match = re.search(r'matrix_(\d+)\.h', matrix_file.name)
        if match:
            idx = int(match.group(1))
            try:
                A, B, C = MatrixHeaderParser.parse_header(str(matrix_file), dim)
                matrix_pairs[idx] = MatrixPair(idx, A, B, C)
            except Exception as e:
                if args.verbose:
                    print(f"  Warning: Could not parse {matrix_file}: {e}")
    
    print(f"  Loaded {len(matrix_pairs)} matrix pairs")
    if args.verbose and matrix_files:
        print(f"  Matrix file indices: {sorted(list(matrix_pairs.keys())[:5])}...")
    print()
    
    # Filter to only use traces where we have matrix data
    common_indices = sorted(set(traces_dict.keys()) & set(matrix_pairs.keys()))
    if not common_indices:
        print("ERROR: No common indices between traces and matrices")
        sys.exit(1)
    
    A_list = [matrix_pairs[i].A for i in common_indices]
    measured_traces_list = [traces_dict[i] for i in common_indices]
    
    print(f"  Using {len(common_indices)} traces with matching matrices")
    print()
    
    # Initialize attack
    print(f"Starting CPA attack...")
    print(f"  Attacking matrix B ({matrix_size} bytes)")
    attack = CPAAttack(dim=dim)
    
    # Determine byte range
    start_byte = args.start_byte
    max_bytes = args.max_bytes if args.max_bytes else matrix_size
    end_byte = min(start_byte + max_bytes, matrix_size)
    
    if start_byte > 0 or end_byte < matrix_size:
        print(f"  Byte range: {start_byte} to {end_byte-1}")
    print()
    
    # Recover each byte
    recovered_B = np.zeros((dim, dim), dtype=np.int8)
    results = []
    
    for byte_idx in range(start_byte, end_byte):
        if args.verbose:
            print(f"  Attacking byte {byte_idx}/{matrix_size-1}...", end='', flush=True)
        else:
            if byte_idx % 4 == 0:
                print(f"  Progress: {byte_idx}/{matrix_size}", end='\r', flush=True)
        
        # Perform attack
        recovered_value, correlations = attack.attack_byte(
            A_list, measured_traces_list, byte_idx, metric=metric
        )
        
        # Convert back to signed int8
        signed_value = np.int8(recovered_value - 128)
        row = byte_idx // dim
        col = byte_idx % dim
        recovered_B[row, col] = signed_value
        
        max_corr = max(correlations)
        results.append({
            'byte_idx': byte_idx,
            'row': row,
            'col': col,
            'recovered': recovered_value,
            'signed': int(signed_value),
            'max_correlation': max_corr
        })
        
        if args.verbose:
            print(f" -> {recovered_value} (corr: {max_corr:.4f})")
    
    print()
    print("=" * 80)
    print("Attack Results")
    print("=" * 80)
    print()
    
    # Display recovered matrix
    print("Recovered Matrix B:")
    print(recovered_B)
    print()
    
    # Show correlation statistics
    correlations = [r['max_correlation'] for r in results]
    print(f"Correlation Statistics:")
    print(f"  Min:  {min(correlations):.4f}")
    print(f"  Max:  {max(correlations):.4f}")
    print(f"  Mean: {np.mean(correlations):.4f}")
    print(f"  Std:  {np.std(correlations):.4f}")
    print()
    
    # Verify if we have expected B
    if all(mp.B_expected is not None for mp in matrix_pairs.values()):
        expected_B = matrix_pairs[common_indices[0]].B_expected  # All should be the same
        match_count = np.sum(recovered_B == expected_B)
        accuracy = (match_count / matrix_size) * 100
        
        print(f"Verification (if matrix B was constant):")
        print(f"  Expected Matrix B:")
        print(f"  {expected_B}")
        print()
        print(f"  Matching bytes: {match_count}/{matrix_size} ({accuracy:.1f}%)")
        print()
    
    # Write results to file
    output_file = args.output
    with open(output_file, 'w') as f:
        f.write("Correlation Power Analysis Attack Results\n")
        f.write("=" * 80 + "\n\n")
        f.write(f"Configuration:\n")
        f.write(f"  Matrix dimension: {dim}x{dim}\n")
        f.write(f"  Power metric: {metric.upper()}\n")
        f.write(f"  Traces used: {len(common_indices)}\n\n")
        
        f.write("Recovered Matrix B:\n")
        f.write(f"{recovered_B}\n\n")
        
        f.write("Detailed Results:\n")
        f.write("Byte,Row,Col,Recovered(unsigned),Signed,MaxCorrelation\n")
        for r in results:
            f.write(f"{r['byte_idx']},{r['row']},{r['col']},{r['recovered']},{r['signed']},{r['max_correlation']:.6f}\n")
    
    print(f"Results written to: {output_file}")
    print()
    print("Done!")

if __name__ == '__main__':
    main()
