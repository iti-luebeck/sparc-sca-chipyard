class CPAAttack:
    """Performs Correlation Power Analysis attack"""
    
    def __init__(self, dim: int = 4):
        """
        Initialize CPA attack.
        
        Args:
            dim: Matrix dimension (default: 4x4)
        """
        self.dim = dim
        self.matrix_size = dim * dim
        
    def generate_hypothesis(self, A: np.ndarray, B_byte_guess: int, 
                           target_byte: int, metric: str = 'hamming') -> np.ndarray:
        """
        Generate hypothetical power trace for a specific byte guess of matrix B.
        
        This computes the Hamming weight of intermediate values during
        matrix multiplication with known input A and guessed B value.
        
        Args:
            A: Known input matrix A (dim x dim)
            B_byte_guess: Guessed byte value (0-255 unsigned) for one element of B
            target_byte: Which byte of matrix B are we targeting (0 to dim*dim-1)
            metric: 'hamming' for Hamming weight of intermediate results
        
        Returns:
            Hypothesis array (simulated power consumption per cycle)
        """
        hypothesis = []
        
        # Convert unsigned (0-255) to signed (-128 to 127) for int8_t interpretation
        B_signed = np.int8(B_byte_guess - 128)
        
        # Simulate matrix multiplication operations
        # For each output element C[i][j], we compute dot product with guessed B
        for out_i in range(self.dim):
            for out_j in range(self.dim):
                # Compute partial products and accumulate
                accumulator = 0
                
                for k in range(self.dim):
                    a_val = int(A[out_i, k])
                    
                    # If target is in this row of B, use guess; otherwise use 0
                    if target_byte // self.dim == k:
                        b_col = target_byte % self.dim
                        if out_j == b_col:
                            b_val = int(B_signed)
                        else:
                            b_val = 0
                    else:
                        b_val = 0
                    
                    product = a_val * b_val
                    accumulator += product
                    
                    # Record Hamming weight of each intermediate
                    if metric == 'hamming':
                        hw = bin(abs(accumulator) & 0xFFFFFFFF).count('1')
                        hypothesis.append(float(hw))
        
        return np.array(hypothesis, dtype=np.float64)
    
    def compute_correlation(self, hypothesis: np.ndarray, trace: np.ndarray) -> float:
        """
        Compute Pearson correlation coefficient between hypothesis and trace.
        
        Args:
            hypothesis: Hypothetical power trace
            trace: Measured power trace
        
        Returns:
            Correlation coefficient (-1.0 to 1.0)
        """
        # Align traces
        min_len = min(len(hypothesis), len(trace))
        hypothesis = hypothesis[:min_len]
        trace = trace[:min_len]
        
        try:
            corr, _ = pearsonr(hypothesis, trace)
            return float(corr) if not np.isnan(corr) else 0.0
        except Exception:
            return 0.0
    
    def attack_byte(self, A_traces: List[np.ndarray], measured_traces: List[np.ndarray],
                    target_byte: int, metric: str = 'hamming') -> Tuple[int, List[float]]:
        """
        Perform CPA attack on a single byte of matrix B.
        
        Args:
            A_traces: List of known input matrices A
            measured_traces: List of measured power traces
            target_byte: Which byte of B to recover (0 to dim*dim-1)
            metric: Power metric ('hamming' or 'value')
        
        Returns:
            (recovered_byte, correlation_scores)
        """
        best_byte = 0
        best_corr = 0.0
        correlations = []
        
        # Try all possible byte values (0-255 for unsigned int8_t)
        for guess in range(256):
            # Compute average correlation across all traces
            correlations_for_guess = []
            
            for A, trace in zip(A_traces, measured_traces):
                hypothesis = self.generate_hypothesis(A, guess, target_byte, metric)
                corr = self.compute_correlation(hypothesis, trace)
                correlations_for_guess.append(corr)
            
            avg_corr = np.mean(correlations_for_guess)
            correlations.append(avg_corr)
            
            if abs(avg_corr) > abs(best_corr):
                best_corr = avg_corr
                best_byte = guess
        
        return best_byte, correlations

